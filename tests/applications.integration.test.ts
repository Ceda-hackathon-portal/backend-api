import { test } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import { PrismaClient } from '../src/generated/prisma/client.js';
import { PrismaPg } from '@prisma/adapter-pg';
import { ApplicationService } from '../src/modules/applications/service.js';
import { PrismaApplicationRepository } from '../src/modules/applications/repository.js';
import { attachFixtureTechnicalProposal, requiredFixtureBudget } from './support/valid-submission-fixture.js';
test('persistent application ownership, concurrent receipts, immutable snapshots and rollback', async () => {
    assert.match(process.env.DISPOSABLE_DATABASE_RUN ?? '', /^[a-f0-9-]{36}$/);
    const url = process.env.DATABASE_URL!;
    assert.equal(new URL(url).hostname, '127.0.0.1');
    const db = new PrismaClient({ adapter: new PrismaPg({ connectionString: url, options: '-c timezone=UTC', max: 8 }) });
    try {
        const user = await db.authUser.create({ data: { email: randomUUID() + '@example.test', name: 'Fictional applicant' } });
        const other = await db.authUser.create({ data: { email: randomUUID() + '@example.test', name: 'Other applicant' } });
        const makeSession = (userId: string) => db.authSession.create({ data: { userId, tokenHash: randomUUID().replaceAll('-', '').repeat(2), idleExpiresAt: new Date(Date.now() + 600000), absoluteExpiresAt: new Date(Date.now() + 1200000) } });
        const session = await makeSession(user.id), otherSession = await makeSession(other.id);
        const principal = { userId: user.id, sessionId: session.id, authnLevel: 'oidc' };
        const requestId = randomUUID();
        const service = new ApplicationService(new PrismaApplicationRepository(db, principal, requestId));
        const otherService = new ApplicationService(new PrismaApplicationRepository(db, { ...principal, userId: other.id, sessionId: otherSession.id }, randomUUID()));
        const programme = await db.programme.create({ data: { code: randomUUID(), name: 'Fictional programme' } });
        const version = await db.programmeVersion.create({ data: { programmeId: programme.id, version: 1, publishedAt: new Date(Date.now() - 10000), opensAt: new Date(Date.now() - 10000), closesAt: new Date(Date.now() + 600000), config: { themes: ['digital'] } } });
        const app = await service.create(principal, programme.id, version.id);
        assert.equal((await service.read(principal, app.id)).ownerId, user.id);
        await assert.rejects(otherService.read({ ...principal, userId: other.id, sessionId: otherSession.id }, app.id), { status: 404 });
        await assert.rejects(service.create(principal, randomUUID(), version.id), { status: 404 });
        await assert.rejects(service.submit(principal, app.id, 0, 'invalid'), { status: 422 });
        const fields = { title: 'Idea', theme: 'digital', problem: 'Problem', solution: 'Solution', impact: 'Impact', team: 'Team' };
        await service.update(principal, app.id, 0, fields, requiredFixtureBudget);
        await attachFixtureTechnicalProposal(db, app.id, user.id);
        await assert.rejects(service.update(principal, app.id, 0, fields), { status: 409 });
        const [a, b] = await Promise.all([service.submit(principal, app.id, 1, 'same'), service.submit(principal, app.id, 1, 'same')]);
        assert.deepEqual(a, b);
        assert.equal(await db.submissionVersion.count({ where: { applicationId: app.id } }), 1);
        assert.equal(await db.commandReceipt.count({ where: { applicationId: app.id } }), 1);
        await assert.rejects(service.submit(principal, app.id, 0, 'same'), { status: 409 });
        await assert.rejects(service.submit(principal, app.id, 1, 'different'), { status: 409 });
        await assert.rejects(db.submissionVersion.update({ where: { id: a.id }, data: { fields: { title: 'tampered' } } }));
        await assert.rejects(db.programmeVersion.update({ where: { id: version.id }, data: { config: { themes: ['changed'] } } }));
        const events = await db.auditEvent.findMany({ where: { applicationId: app.id }, include: { outbox: true } });
        assert.equal(events.length, 3);
        assert.ok(events.every(e => e.requestId === requestId && e.actorId === user.id && e.outbox.length === 1));
        const rollback = await service.create(principal, programme.id, version.id);
        await service.update(principal, rollback.id, 0, fields, requiredFixtureBudget);
        await attachFixtureTechnicalProposal(db, rollback.id, user.id);
        // A fixture trigger forces the submission audit insert to fail inside the command transaction.
        await db.$executeRawUnsafe("CREATE FUNCTION fail_test_audit() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF NEW.action='application.submitted' AND NEW.application_id='" + rollback.id + "'::uuid THEN RAISE EXCEPTION 'test audit failure'; END IF; RETURN NEW; END $$");
        await db.$executeRawUnsafe('CREATE TRIGGER test_audit_failure BEFORE INSERT ON audit_events FOR EACH ROW EXECUTE FUNCTION fail_test_audit()');
        await assert.rejects(service.submit(principal, rollback.id, 1, 'rollback'));
        assert.equal((await db.application.findUniqueOrThrow({ where: { id: rollback.id } })).stage, 'DRAFT');
        assert.equal(await db.submissionVersion.count({ where: { applicationId: rollback.id } }), 0);
        assert.equal(await db.commandReceipt.count({ where: { applicationId: rollback.id } }), 0);
        await db.$executeRawUnsafe('DROP TRIGGER test_audit_failure ON audit_events');
        const repository = new PrismaApplicationRepository(db, principal, requestId);
        const checkPermission = (id: string) => repository.transaction(async (tx) => { await tx.requireSession(principal); await tx.requireProgrammePermission(id, 'programme.manage'); });
        await assert.rejects(checkPermission(programme.id), { status: 403 });
        const grant = await db.programmeGrant.create({ data: { userId: user.id, programmeId: programme.id, permission: 'programme.manage', grantedById: user.id } });
        await checkPermission(programme.id);
        await assert.rejects(checkPermission(randomUUID()), { status: 403 });
        await assert.rejects(db.programmeGrant.create({ data: { userId: user.id, programmeId: programme.id, permission: 'programme.manage', grantedById: user.id } }));
        await db.programmeGrant.update({ where: { id: grant.id }, data: { revokedAt: new Date() } });
        await assert.rejects(checkPermission(programme.id), { status: 403 });
        await assert.rejects(db.application.create({ data: { ownerId: user.id, programmeId: programme.id, programmeVersionId: version.id, draft: fields } }));
        await assert.rejects(db.application.create({ data: { ownerId: user.id, programmeId: randomUUID(), programmeVersionId: version.id, draft: fields } }));
        await assert.rejects(db.submissionVersion.create({ data: { applicationId: app.id, programmeVersionId: version.id, version: 2, revision: 3, reference: randomUUID(), fields } }));
        await assert.rejects(db.auditEvent.delete({ where: { id: events[0]!.id } }));
        const receipt = await db.commandReceipt.findFirstOrThrow({ where: { applicationId: app.id } });
        await assert.rejects(db.commandReceipt.delete({ where: { id: receipt.id } }));
        await db.$executeRawUnsafe("CREATE FUNCTION fail_test_outbox() RETURNS trigger LANGUAGE plpgsql AS $$ BEGIN IF EXISTS(SELECT 1 FROM audit_events WHERE id=NEW.audit_event_id AND application_id='" + rollback.id + "'::uuid) THEN RAISE EXCEPTION 'test outbox failure'; END IF; RETURN NEW; END $$");
        await db.$executeRawUnsafe('CREATE TRIGGER test_outbox_failure BEFORE INSERT ON outbox_events FOR EACH ROW EXECUTE FUNCTION fail_test_outbox()');
        await assert.rejects(service.submit(principal, rollback.id, 1, 'outbox-failure'));
        assert.equal(await db.submissionVersion.count({ where: { applicationId: rollback.id } }), 0);
        assert.equal((await db.application.findUniqueOrThrow({ where: { id: rollback.id } })).revision, 1);
        await db.$executeRawUnsafe('DROP TRIGGER test_outbox_failure ON outbox_events');
        const expired = await makeSession(user.id);
        await db.authSession.update({ where: { id: expired.id }, data: { idleExpiresAt: new Date(0) } });
        const expiredPrincipal = { ...principal, sessionId: expired.id };
        await assert.rejects(new ApplicationService(new PrismaApplicationRepository(db, expiredPrincipal, randomUUID())).read(expiredPrincipal, app.id), { status: 401 });
        await db.authSession.update({ where: { id: session.id }, data: { revokedAt: new Date() } });
        await assert.rejects(service.read(principal, app.id), { status: 401 });
        const fresh = await makeSession(user.id);
        const freshPrincipal = { ...principal, sessionId: fresh.id };
        const freshService = new ApplicationService(new PrismaApplicationRepository(db, freshPrincipal, randomUUID()));
        await db.authUser.update({ where: { id: user.id }, data: { status: 'SUSPENDED' } });
        await assert.rejects(freshService.read(freshPrincipal, app.id), { status: 401 });
    }
    finally {
        await db.$disconnect();
    }
});
